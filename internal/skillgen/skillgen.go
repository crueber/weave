// Package skillgen renders the Claude-Code-compatible Weave skill (skills/weave) and the CLI's
// offline schema snapshot from the op registry, merged with hand-written guidance in src/.
// Output is deterministic (no timestamps or versions) so a test can detect staleness.
package skillgen

import (
	"embed"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/crueber/weave/internal/cli"
)

//go:generate go run ../../cmd/weave-skillgen -root ../..

//go:embed src/*.md
var src embed.FS

const regenHint = "Run `make skill` to regenerate."

func read(name string) string {
	b, err := src.ReadFile("src/" + name)
	if err != nil {
		panic(err)
	}
	return string(b)
}

// Render returns repo-relative path -> content for everything the generator owns.
// base is the op schema as served by the registry (without the CLI's contract overlay).
func Render(base []cli.Op) map[string][]byte {
	sorted := append([]cli.Op{}, base...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	snap, _ := json.MarshalIndent(sorted, "", " ")
	merged := cli.MergedOps(base)

	skill := strings.ReplaceAll(read("SKILL.md"), "{{OPS_COUNT}}", fmt.Sprint(len(merged)))
	out := map[string][]byte{
		"internal/cli/snapshot.json":                 append(snap, '\n'),
		"skills/weave/SKILL.md":                      []byte(skill),
		"skills/weave/references/commands.md":        []byte(read("commands.md")),
		"skills/weave/references/agent-workflows.md": []byte(read("agent-workflows.md")),
		"skills/weave/references/events.md":          []byte(read("events.md")),
		"skills/weave/references/ops.md":             []byte(renderOps(merged)),
		// Compact form for tools that only read instruction/rules files (AGENTS.md, GEMINI.md, .mdc ...).
		"skills/instructions.md": []byte(read("INSTRUCTIONS.md")),
	}
	return out
}

func renderOps(ops []*cli.Op) string {
	var sb strings.Builder
	sb.WriteString("# Weave op reference (generated)\n\n")
	sb.WriteString("<!-- GENERATED by `make skill` from the op registry; do not edit. -->\n\n")
	sb.WriteString("Every op is callable as `weave <tag> <verb>` (op `a.b.c` is `weave a b.c`). Path fields can be given positionally.\n")
	sb.WriteString("The server is the source of truth: `weave ops` / `weave schema OP` show what *your* server supports.\n\n")
	byTag := map[string][]*cli.Op{}
	var tags []string
	for _, o := range ops {
		if _, ok := byTag[o.Tag]; !ok {
			tags = append(tags, o.Tag)
		}
		byTag[o.Tag] = append(byTag[o.Tag], o)
	}
	sort.Strings(tags)
	sb.WriteString("Tags: " + strings.Join(tags, ", ") + "\n\n")
	for _, t := range tags {
		fmt.Fprintf(&sb, "## %s\n\n", t)
		for _, o := range byTag[t] {
			fmt.Fprintf(&sb, "### `weave %s %s`\n\n%s  \n`%s %s` (auth: %s)\n\n", o.Tag, o.Verb(), strings.TrimSpace(o.Summary), o.Method, o.Path, o.Auth)
			if len(o.Fields) > 0 {
				sb.WriteString("| flag | in | type | required | description |\n|---|---|---|---|---|\n")
				for _, f := range o.Fields {
					req := ""
					if f.Required {
						req = "yes"
					}
					fmt.Fprintf(&sb, "| `--%s` | %s | %s | %s | %s |\n", f.Name, f.In, f.Type, req, strings.ReplaceAll(f.Desc, "|", "\\|"))
				}
				sb.WriteString("\n")
			}
		}
	}
	return sb.String()
}

// RegenHint is the message tests print when generated output is stale.
func RegenHint() string { return regenHint }
