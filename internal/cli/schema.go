// Field and Op mirror ops.Field / ops.Schema (the JSON shape of GET /api/v1/_ops) so the CLI
// never imports internal/ops (which links the database) and can ship as a slim binary.
type Field struct {
	Name     string `json:"name"`
	In       string `json:"in"` // path | query | body | file
	Type     string `json:"type"`
	Required bool   `json:"required"`
	Desc     string `json:"desc,omitempty"`
}

type Op struct {
	Name    string  `json:"name"`
	Tag     string  `json:"tag"`
	Summary string  `json:"summary"`
	Method  string  `json:"method"`
	Path    string  `json:"path"`
	Auth    string  `json:"auth"`
	UI      string  `json:"ui"`
	Fields  []Field `json:"fields"`
}

// Verb is the op name after the tag ("card.label.add" -> "label.add").
func (o *Op) Verb() string {
	_, v, _ := strings.Cut(o.Name, ".")
	if v == "" {
		return o.Name
	}
	return v
}

func (o *Op) Field(name string) *Field {
	for i := range o.Fields {
		if o.Fields[i].Name == name {
			return &o.Fields[i]
		}
	}
	return nil
}

//go:embed snapshot.json
var snapshotJSON []byte

// LocalSchema is set by the full binary (cmd/weave) to expose the live in-process registry.
var LocalSchema func() []Op

// SnapshotOps returns the embedded offline schema snapshot (generated by `make skill`).
func SnapshotOps() []Op {
	ops, _ := parseOps(snapshotJSON)
	return ops
}

// parseOps accepts the shapes a server may reasonably return: a bare array,
// {"items":[...]}, {"ops":[...]} or {"item":{"ops":[...]}}.
func parseOps(b []byte) ([]Op, string) {
	var arr []Op
	if json.Unmarshal(b, &arr) == nil && len(arr) > 0 {
		return arr, ""
	}
	var env struct {
		Items   []Op   `json:"items"`
		Ops     []Op   `json:"ops"`
		Version string `json:"version"`
		Item    struct {
			Ops     []Op   `json:"ops"`
			Items   []Op   `json:"items"`
			Version string `json:"version"`
		} `json:"item"`
	}
	if json.Unmarshal(b, &env) != nil {
		return nil, ""
	}
	for _, c := range [][]Op{env.Items, env.Ops, env.Item.Ops, env.Item.Items} {
		if len(c) > 0 {
			v := env.Version
			if v == "" {
				v = env.Item.Version
			}
			return c, v
		}
	}
	return nil, ""
}

// Catalog is the set of ops the CLI can call.
type Catalog struct {
	byName map[string]*Op
	Source string // server | cache | local | snapshot
}

func newCatalog(src string, lists ...[]Op) *Catalog {
	c := &Catalog{byName: map[string]*Op{}, Source: src}
	for _, l := range lists {
		for i := range l {
			if _, ok := c.byName[l[i].Name]; !ok {
				op := l[i]
				c.byName[op.Name] = &op
			}
		}
	}
	applyOverlay(c)
	return c
}

func (c *Catalog) Get(name string) *Op { return c.byName[name] }

func (c *Catalog) All() []*Op {
	out := make([]*Op, 0, len(c.byName))
	for _, o := range c.byName {
		out = append(out, o)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func (c *Catalog) Tags() []string {
	seen := map[string]bool{}
	var tags []string
	for _, o := range c.All() {
		if !seen[o.Tag] {
			seen[o.Tag] = true
			tags = append(tags, o.Tag)
		}
	}
	return tags
}

func (c *Catalog) Tag(tag string) []*Op {
	var out []*Op
	for _, o := range c.All() {
		if o.Tag == tag {
			out = append(out, o)
		}
	}
	return out
}

// Lookup finds "<tag> <verb...>".
func (c *Catalog) Lookup(tag, verb string) *Op { return c.byName[tag+"."+verb] }

// MergedOps returns the full op list as the CLI sees it offline (given ops + contract overlay);
// used by the skill generator.
func MergedOps(base []Op) []*Op { return newCatalog("merged", base).All() }

type cacheFile struct {
	URL       string    `json:"url"`
	Version   string    `json:"version"`
	FetchedAt time.Time `json:"fetchedAt"`
	Ops       []Op      `json:"ops"`
}

func cacheDir() string {
	if d := os.Getenv("WEAVE_CACHE_DIR"); d != "" {
		return d
	}
	d, err := os.UserCacheDir()
	if err != nil || d == "" {
		// never fall back to a shared, world-writable directory such as /tmp
		h, herr := os.UserHomeDir()
		if herr != nil || h == "" {
			return ""
		}
		d = filepath.Join(h, ".cache")
	}
	return filepath.Join(d, "weave")
}

func schemaCachePath(url string) string {
	if cacheDir() == "" {
		return ""
	}
	return filepath.Join(cacheDir(), "ops-"+shortHash(strings.TrimRight(url, "/"))+".json")
}

const schemaTTL = time.Hour

// loadCatalog resolves the schema: server /_ops (cached on disk per server) -> local
// registry (full binary) -> embedded snapshot, always topped up by the contract overlay.
func (a *App) loadCatalog(ctx context.Context, offline, refresh bool) *Catalog {
	a.catMu.Lock()
	defer a.catMu.Unlock()
	if a.catalog != nil && !refresh {
		return a.catalog
	}
	var cat *Catalog
	if !offline {
		cat = a.catalogFromServer(ctx, refresh)
	} else if cf := a.readCache(); cf != nil {
		cat = newCatalog("cache", cf.Ops)
	}
	if cat == nil {
		if LocalSchema != nil {
			cat = newCatalog("local", LocalSchema())
		} else {
			cat = newCatalog("snapshot", SnapshotOps())
		}
	}
	a.catalog = cat
	return cat
}

func (a *App) readCache() *cacheFile {
	if schemaCachePath(a.Cfg.URL) == "" {
		return nil
	}
	b, err := os.ReadFile(schemaCachePath(a.Cfg.URL))
	if err != nil {
		return nil
	}
	var cf cacheFile
	if json.Unmarshal(b, &cf) != nil || len(cf.Ops) == 0 {
		return nil
	}
	return &cf
}

func (a *App) catalogFromServer(ctx context.Context, refresh bool) *Catalog {
	cf := a.readCache()
	if cf != nil && !refresh && time.Since(cf.FetchedAt) < schemaTTL {
		return newCatalog("cache", cf.Ops)
	}
	if a.Cfg.URL == "" || os.Getenv("WEAVE_NO_SCHEMA_FETCH") != "" {
		if cf != nil {
			return newCatalog("cache", cf.Ops)
		}
		return nil
	}
	ctx, cancel := context.WithTimeout(ctx, 4*time.Second)
	defer cancel()
	req, _ := http.NewRequestWithContext(ctx, "GET", strings.TrimRight(a.Cfg.URL, "/")+"/api/v1/_ops", nil)
	if a.Cfg.Token != "" {
		req.Header.Set("Authorization", "Bearer "+a.Cfg.Token)
	}
	resp, err := a.httpClient(0).Do(req)
	if err == nil {
		defer resp.Body.Close()
		if resp.StatusCode == 200 {
			b, _ := io.ReadAll(io.LimitReader(resp.Body, 16<<20))
			if ops, ver := parseOps(b); len(ops) > 0 {
				if ver == "" {
					ver = resp.Header.Get("X-Weave-Version")
				}
				a.writeCache(cacheFile{URL: a.Cfg.URL, Version: ver, FetchedAt: time.Now(), Ops: ops})
				return newCatalog("server", ops)
			}
		}
	}
	if cf != nil { // stale cache beats nothing
		return newCatalog("cache", cf.Ops)
	}
	return nil
}

func (a *App) writeCache(cf cacheFile) {
	b, err := json.Marshal(cf)
	if err != nil {
		return
	}
	if schemaCachePath(cf.URL) == "" {
		return
	}
	if ensurePrivateDir(cacheDir()) != nil {
		return
	}
	_ = atomicWrite(schemaCachePath(cf.URL), b, 0o600)
}

func (a *App) mustOp(name string) (*Op, error) {
	cat := a.loadCatalog(context.Background(), false, false)
	if o := cat.Get(name); o != nil {
		return o, nil
	}
	return nil, &APIError{Code: "usage", Message: fmt.Sprintf("this server does not support op %q (see `weave ops`)", name)}
}
